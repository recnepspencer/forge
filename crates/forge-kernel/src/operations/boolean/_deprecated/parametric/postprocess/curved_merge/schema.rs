//! Data shapes for curved same-support surface merge.
//!
//! DOMAIN: Defines the intent/execution/result split for curved merge
//! operations. These types are architectural placeholders following the
//! Epic B pattern (MergeRegionSelection → MergePlan → execution).
//!
//! DEPENDENCIES: forge-topo handles, worth-geom surface types

use forge_topo::handles::{CoedgeRef, CurveRef, FaceId, SurfaceRef};
use serde::{Deserialize, Serialize};

/// Agent-facing merge intent for curved same-support faces.
///
/// Serializable and stable across topology mutations. The kernel
/// derives a snapshot-scoped `CurvedMergePlan` from this selection.
///
/// DESIGN TARGET: Not yet consumed by any execution path.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CurvedMergeSelection {
    /// Faces selected for merge (must all share the same support surface).
    pub selected_faces: Vec<FaceId>,
    /// Faces adjacent to the selection that must not be disturbed.
    pub protected_faces: Vec<FaceId>,
    /// The face that survives the merge (inherits the SurfaceRef).
    pub surviving_face: FaceId,
    /// Policy overrides for this specific merge (if any).
    pub policy_overrides: CurvedMergePolicyOverrides,
}

/// Policy overrides for curved merge eligibility.
///
/// All fields are `Option` — `None` means "use kernel default".
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CurvedMergePolicyOverrides {
    /// Override the normal-continuity tolerance (radians).
    pub normal_continuity_tol: Option<f64>,
    /// Override the UV-space trim overlap tolerance.
    pub trim_overlap_tol: Option<f64>,
    /// Allow merge even when SurfaceRelation is Undetermined.
    /// Default: false (fail-closed).
    pub allow_undetermined: Option<bool>,
}

/// Kernel-derived deterministic execution blueprint for curved merge.
///
/// Snapshot-scoped — handles and indices are valid only for the
/// topology/geometry snapshot that produced this plan.
///
/// DESIGN TARGET: Not yet generated by any execution path.
#[derive(Debug, Clone)]
pub struct CurvedMergePlan {
    /// Ordered merge steps (deterministically sorted).
    pub steps: Vec<CurvedMergeStep>,
    /// Hash over the step sequence for traceability.
    pub plan_hash: u64,
    /// The shared SurfaceRef for all faces in the selection.
    pub shared_surface: SurfaceRef,
}

/// One step in a curved merge plan.
#[derive(Debug, Clone)]
pub struct CurvedMergeStep {
    /// Index of the shared edge to merge across.
    pub edge_index: u32,
    /// Indices of the two faces being merged at this edge.
    pub face_indices: [u32; 2],
    /// Coedges that must be rebuilt after this merge step.
    pub affected_coedges: Vec<CoedgeRef>,
    /// Curves that must be rebuilt after this merge step.
    pub affected_curves: Vec<CurveRef>,
}

/// Result of a successful curved merge execution.
///
/// DESIGN TARGET: Not yet returned by any execution path.
#[derive(Debug, Clone)]
pub struct CurvedMergeResult {
    /// The surviving face after merge.
    pub surviving_face: FaceId,
    /// Faces killed during merge.
    pub killed_faces: Vec<FaceId>,
    /// Coedges that were rebuilt (new CoedgeRefs replacing old ones).
    pub rebuilt_coedges: Vec<(CoedgeRef, CoedgeRef)>,
    /// Curves that were rebuilt (new CurveRefs replacing old ones).
    pub rebuilt_curves: Vec<(CurveRef, CurveRef)>,
}
